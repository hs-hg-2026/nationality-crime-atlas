import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const EXPECTED_MAP_ASSET_SHA256 =
  'c4817c97dedab08d20a2f4afccd4a780befc57040d48f7f0cded79d10e084fbc';

function optionUrl(flag, fallback) {
  const index = process.argv.indexOf(flag);
  if (index === -1) return fallback;
  const value = process.argv[index + 1];
  if (!value || value.startsWith('--')) {
    throw new Error(`${flag} requires a file path.`);
  }
  return pathToFileURL(resolve(value));
}

const sourceUrl = optionUrl(
  '--source',
  new URL('../assets/maps/deformed-japan-prefecture-map.svg', import.meta.url),
);
const outputUrl = optionUrl(
  '--output',
  new URL('../lib/japan-map-paths.generated.ts', import.meta.url),
);
const sourceBytes = readFileSync(sourceUrl);
const sourceSha256 = createHash('sha256').update(sourceBytes).digest('hex');
if (sourceSha256 !== EXPECTED_MAP_ASSET_SHA256) {
  throw new Error(
    `Map asset SHA-256 mismatch: expected ${EXPECTED_MAP_ASSET_SHA256}, received ${sourceSha256}.`,
  );
}
const source = sourceBytes.toString('utf8');
const pathPattern =
  /<path id="area_(\d{3})" data-code="(\d+)" data-name="([^"]+)" d="([^"]+)" fill="white" stroke="none"\/>/g;
const paths = [...source.matchAll(pathPattern)].map((match) => ({
  code: match[2].padStart(2, '0'),
  name: match[3],
  d: match[4],
}));
const borderPath = source.match(
  /<path id="prefecture-borders" d="([^"]+)"/u,
)?.[1];

if (paths.length !== 47) {
  throw new Error(`Expected 47 prefecture paths, found ${paths.length}.`);
}
if (new Set(paths.map((path) => path.code)).size !== 47) {
  throw new Error('Prefecture codes are not unique.');
}
if (!borderPath) {
  throw new Error('Prefecture border overlay is missing.');
}

function quoteTypeScriptString(value) {
  return `'${value
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "\\'")
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')}'`;
}

const pathEntries = paths
  .map(
    (path) =>
      `  {\n` +
      `    code: ${quoteTypeScriptString(path.code)},\n` +
      `    name: ${quoteTypeScriptString(path.name)},\n` +
      `    d: ${quoteTypeScriptString(path.d)},\n` +
      `  },`,
  )
  .join('\n');
const output =
  `// Generated by scripts/generate-japan-map-data.mjs from the pinned CC0 asset.\n` +
  `// Do not edit by hand. See assets/maps/README.md for provenance.\n\n` +
  `export const JAPAN_PREFECTURE_PATHS = [\n${pathEntries}\n] as const;\n\n` +
  `export const JAPAN_PREFECTURE_BORDER_PATH =\n` +
  `  ${quoteTypeScriptString(borderPath)};\n`;

writeFileSync(outputUrl, output, 'utf8');
